def test_provenance_classification_script_vs_human():
    """
    Issue 1 Audit: Verify that data generated by execute_live_pilot_cohort.py is 
    classified as SYNTHETIC / OPERATIONAL DRY RUN, not Live Human Pilot.
    """
    # Cohort generated via script with synthetic prefix p_pilot_
    sample_participant_ids = [f"p_pilot_{i:02d}" for i in range(1, 19)]
    
    # Classification check: script-generated UUIDs belong to Operational Dry Run
    is_scripted_dry_run = all(pid.startswith("p_pilot_") for pid in sample_participant_ids)
    assert is_scripted_dry_run is True

    # Authentic human pilot participants generated via API endpoint generate UUIDs format p_<uuid4>
    human_participant = Participant(participant_id="p_9b1deb4d-3b7d-4bad-9bdd-2b0d7b3d0d12")
    assert not human_participant.participant_id.startswith("p_pilot_")


